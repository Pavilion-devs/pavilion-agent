"""Generate the Zetaris SQL that onboards the SEC EDGAR sources for our universe.

Reads zetaris_sql/universe.json and writes:
  zetaris_sql/sources/01_edgar_facts.sql        one cached REST table per (company, metric)
                                                 + edgar.financial_fact, a single canonical view
  zetaris_sql/sources/02_edgar_submissions.sql  one cached REST table per company
                                                 + edgar.company, the company dimension

Pattern follows Zetaris's getting-started recipes 01 and 11 (REST table, CACHE
TABLE straight away, SCHEMASTORE view with LATERAL VIEW explode).
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UNIVERSE = json.loads((ROOT / "zetaris_sql" / "universe.json").read_text())
OUT = ROOT / "zetaris_sql" / "sources"
UA = "YOUR_APP_NAME YOUR_CONTACT_EMAIL"  # filled from SEC_USER_AGENT by scripts/run_sql.py

# Balance-sheet values are point-in-time: their XBRL facts carry no `start`.
INSTANT_METRICS = {"inventory"}


def rest_table(name: str, endpoint: str) -> str:
    return f"""CREATE LIGHTNING REST TABLE {name} FROM SEC_DATA REQUEST(
    endpoint "{endpoint}",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
    user-agent "{UA}"
) BODY ();
CACHE TABLE sec_data.{name};
"""


def facts_sql() -> str:
    parts = [
        "-- Generated by scripts/gen_edgar_sql.py from zetaris_sql/universe.json. Do not edit by hand.",
        "-- SEC EDGAR companyconcept: one REST table per (company, metric), cached immediately",
        "-- because an uncached REST table re-fetches the endpoint on every query.",
        "-- Licence: filer-authored data, query live, do not bulk-redistribute.",
        "",
        'CREATE LIGHTNING DATABASE SEC_DATA DESCRIBE BY "SEC EDGAR XBRL company concepts for the Causeway retail universe";',
        "CREATE SCHEMASTORE CONTAINER edgar;",
        "",
    ]
    selects = []
    for co in UNIVERSE["companies"]:
        t = co["ticker"].lower()
        for metric, tag in co["tags"].items():
            name = f"{t}_{metric}_raw"
            url = f"https://data.sec.gov/api/xbrl/companyconcept/CIK{co['cik']}/us-gaap/{tag}.json"
            parts.append(f"-- {co['name']} ({co['ticker']}) {metric} = us-gaap:{tag}")
            parts.append(rest_table(name, url))
            start = "CAST(NULL AS STRING)" if metric in INSTANT_METRICS else "fact.`start`"
            selects.append(
                f"""SELECT
    '{co['ticker']}' AS ticker,
    '{metric}' AS metric,
    LPAD(CAST(cik AS STRING), 10, '0') AS cik,
    `entityName` AS entity_name,
    tag AS xbrl_tag,
    {start} AS period_start,
    fact.`end` AS period_end,
    CAST(fact.val AS DOUBLE) AS value_usd,
    fact.accn AS accession_number,
    fact.fy AS fiscal_year,
    fact.fp AS fiscal_period,
    fact.form AS form_type,
    fact.filed AS filed_date,
    fact.frame AS period_frame
FROM sec_data.{name}
LATERAL VIEW explode(units.USD) AS fact"""
            )
    parts.append("-- Canonical fact view: every company's figures under one metric vocabulary.")
    parts.append("CREATE SCHEMASTORE VIEW financial_fact WITH CONTAINER edgar AS")
    parts.append("\nUNION ALL\n".join(selects) + ";")
    return "\n".join(parts) + "\n"


def submissions_sql() -> str:
    parts = [
        "-- Generated by scripts/gen_edgar_sql.py from zetaris_sql/universe.json. Do not edit by hand.",
        "-- SEC EDGAR submissions: company profile (SIC code, fiscal year end), one cached REST table per company.",
        "-- Requires 01_edgar_facts.sql (SEC_DATA database, edgar container).",
        "",
    ]
    selects = []
    for co in UNIVERSE["companies"]:
        name = f"{co['ticker'].lower()}_submissions_raw"
        parts.append(f"-- {co['name']} ({co['ticker']})")
        parts.append(rest_table(name, f"https://data.sec.gov/submissions/CIK{co['cik']}.json"))
        notes = co.get("notes", "").replace("'", "")
        selects.append(
            f"""SELECT
    '{co['ticker']}' AS ticker,
    cik,
    name AS entity_name,
    sic AS sic_code,
    `sicDescription` AS sic_description,
    `fiscalYearEnd` AS fiscal_year_end_mmdd,
    '{notes}' AS comparability_note
FROM sec_data.{name}"""
        )
    parts.append("-- Company dimension for the universe.")
    parts.append("CREATE SCHEMASTORE VIEW company WITH CONTAINER edgar AS")
    parts.append("\nUNION ALL\n".join(selects) + ";")
    return "\n".join(parts) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "01_edgar_facts.sql").write_text(facts_sql())
    (OUT / "02_edgar_submissions.sql").write_text(submissions_sql())
    print("wrote", OUT / "01_edgar_facts.sql", "and", OUT / "02_edgar_submissions.sql")


if __name__ == "__main__":
    main()
